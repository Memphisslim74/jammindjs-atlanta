#!/usr/bin/env node

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ORIGIN = "https://www.jammindjs.net";
const postsDirectory = path.resolve(process.env.CONTENT_POSTS_DIR ?? "content/posts");
const templateFile = path.resolve(
  process.env.BLOG_TEMPLATE_FILE ?? "content/templates/blog-post.html",
);
const publicRoot = path.resolve(process.env.PUBLIC_ROOT ?? "public");

function escapeHtml(value = "") {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function asAbsolute(value, fallback) {
  if (!value) return fallback;
  return new URL(value, ORIGIN).href;
}

function displayDate(value) {
  const calendarDate = new Date(`${value.slice(0, 10)}T12:00:00Z`);
  return new Intl.DateTimeFormat("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
    timeZone: "America/New_York",
  }).format(calendarDate);
}

function renderBody(value = "") {
  if (/<[a-z][\s\S]*>/i.test(value)) return value;
  return value
    .trim()
    .split(/\n{2,}/)
    .map((block) => {
      const heading = block.match(/^(#{1,3})\s+(.+)$/s);
      if (heading) {
        const level = heading[1].length + 1;
        return `<h${level}>${escapeHtml(heading[2])}</h${level}>`;
      }
      return `<p>${escapeHtml(block).replaceAll("\n", "<br>\n")}</p>`;
    })
    .join("\n");
}

function seoHead(post, absoluteUrl, canonical, image) {
  const seoTitle = escapeHtml(
    post.seo_title || `${post.title} - JAMMIN' DJs Georgia & Tennessee`,
  );
  const description = escapeHtml(post.seo_description || post.excerpt || "");
  const title = escapeHtml(post.title);
  const robots = post.status === "publish" ? "index, follow" : "noindex, nofollow";
  const schema = {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: post.title,
    datePublished: new Date(post.date).toISOString(),
    dateModified: new Date(post.modified || post.date).toISOString(),
    mainEntityOfPage: canonical,
    author: { "@type": "Person", name: post.author || "Jammin Blogger" },
    publisher: { "@type": "Organization", name: "JAMMIN' DJs", url: ORIGIN },
    ...(image ? { image: [image] } : {}),
  };
  return `<!-- SEO generated by the JAMMIN' DJs static content build. -->
  <title>${seoTitle}</title>
  <meta name="description" content="${description}" />
  <meta name="robots" content="${robots}, max-image-preview:large" />
  <link rel="canonical" href="${escapeHtml(canonical)}" />
  <meta property="og:type" content="article" />
  <meta property="og:title" content="${title}" />
  <meta property="og:description" content="${description}" />
  <meta property="og:url" content="${escapeHtml(absoluteUrl)}" />
  ${image ? `<meta property="og:image" content="${escapeHtml(image)}" />` : ""}
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${title}" />
  <meta name="twitter:description" content="${description}" />
  <script type="application/ld+json">${JSON.stringify(schema).replaceAll("<", "\\u003c")}</script>`;
}

const template = await readFile(templateFile, "utf8");
const files = (await readdir(postsDirectory)).filter((file) => file.endsWith(".json"));
let built = 0;

for (const file of files) {
  const post = JSON.parse(await readFile(path.join(postsDirectory, file), "utf8"));
  if (!post.managed || post.status !== "publish") continue;

  const urlPath = (post.url || `/blog/${post.slug}/`).replace(/\/+/g, "/");
  const normalizedPath = urlPath.endsWith("/") ? urlPath : `${urlPath}/`;
  const absoluteUrl = `${ORIGIN}${normalizedPath}`;
  const canonical = asAbsolute(post.canonical, absoluteUrl);
  const image = asAbsolute(post.featured_image, "");
  const categoryName = post.category_name || post.categories?.[0]?.name || "Blog";
  const categoryUrl = asAbsolute(
    post.category_url || post.categories?.[0]?.link,
    `${ORIGIN}/blog/`,
  );

  const replacements = {
    "{{SEO_HEAD}}": seoHead(post, absoluteUrl, canonical, image),
    "{{BODY_HTML}}": renderBody(post.body_html),
    "{{ABSOLUTE_URL}}": absoluteUrl,
    "{{ABSOLUTE_URL_ENCODED}}": encodeURIComponent(absoluteUrl),
    "{{CANONICAL}}": canonical,
    "{{CANONICAL_ENCODED}}": encodeURIComponent(canonical),
    "{{TITLE_HTML}}": escapeHtml(post.title),
    "{{TITLE_URLENCODED}}": encodeURIComponent(post.title),
    "{{DISPLAY_DATE}}": displayDate(post.date),
    "{{FEATURED_IMAGE}}": escapeHtml(image),
    "{{FEATURED_IMAGE_ENCODED}}": encodeURIComponent(image),
    "{{FEATURED_IMAGE_ALT}}": escapeHtml(post.featured_image_alt || post.title),
    "{{CATEGORY_NAME}}": escapeHtml(categoryName),
    "{{CATEGORY_URL}}": escapeHtml(categoryUrl),
  };

  let html = template;
  for (const [token, value] of Object.entries(replacements)) {
    html = html.split(token).join(value);
  }
  if (/\{\{[A-Z_]+\}\}/.test(html)) {
    throw new Error(`Unresolved blog template token while building ${file}.`);
  }

  const outputFile = path.join(publicRoot, normalizedPath, "index.html");
  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, html);
  built += 1;
}

console.log(`Built ${built} CMS-managed blog posts.`);
